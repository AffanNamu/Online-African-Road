#!/usr/bin/env python3
"""Generates the idempotent database seeds that mirror authored client data, so the two cannot drift apart:

  supabase/seed_world.sql    <- Assets/_Project/Resources/WorldMap/world_map.json  (countries, cities, routes)
  supabase/seed_content.sql  <- Assets/_Project/Resources/Dashboard/news.json + hero.json (authored news and hero banners)

Usage:  python3 tools/gen_game_seed.py          write the files
        python3 tools/gen_game_seed.py --check  exit 1 if the committed files are stale (used by CI)

Seeds only INSERT missing rows (on conflict do nothing / static columns only): they never overwrite a status or level that
an operator changed in the live database. Authored content is labelled source = 'authored' - it is not external news."""
import json, math, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "Assets", "_Project", "Resources")
OUT = os.path.join(ROOT, "supabase")
WINDING = 1.3   # road distance ~= great-circle distance x 1.3 where no surveyed road length is known


def q(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


def haversine(a, b):
    r = 6371.0
    p1, p2 = math.radians(a["lat"]), math.radians(b["lat"])
    dp, dl = p2 - p1, math.radians(b["lon"] - a["lon"])
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(h))


def world_sql():
    d = json.load(open(os.path.join(RES, "WorldMap", "world_map.json"), encoding="utf-8"))
    cities = {c["id"]: c for c in d["cities"]}
    country_name = {c["code"]: c["name"] for c in d["countries"]}
    open_status = ("live", "prototype")
    routes = []
    for r in d["routes"]:
        legs = list(zip(r["via"], r["via"][1:]))
        if r.get("roadKm"):
            km, src = float(r["roadKm"]), "road"
        else:
            km, src = round(sum(haversine(cities[a], cities[b]) for a, b in legs) * WINDING, 1), "estimated"
        routes.append((r, km, src, "OPEN" if r["status"] in open_status else "PLANNED"))
    city_level, city_open = {}, set()
    for r, _, _, st in routes:
        for c in (r["via"][0], r["via"][-1]):
            city_level[c] = min(city_level.get(c, 99), r["unlockLevel"])
            if st == "OPEN":
                city_open.add(c)
    L = ["-- GENERATED by tools/gen_game_seed.py from Resources/WorldMap/world_map.json. Do not edit by hand.",
         "-- Idempotent: inserts missing rows only; never overwrites a status / level changed in the live database.", ""]
    L.append("insert into countries(code, name) values")
    L.append(",\n".join(f"  ({q(c['code'])}, {q(c['name'])})" for c in d["countries"]))
    L.append("on conflict do nothing;\n")
    L.append("insert into cities(country_code, name, lat, lng, slug, region, status, unlock_level, map_x, map_y) values")
    rows = []
    for c in d["cities"]:
        rows.append(f"  ({q(c['country'])}, {q(c['name'])}, {c['lat']}, {c['lon']}, {q(c['id'])}, {q(country_name[c['country']])}, "
                    f"{q('OPEN' if c['id'] in city_open else 'PLANNED')}, {city_level.get(c['id'], 1)}, {c['mapX']}, {c['mapY']})")
    L.append(",\n".join(rows))
    L.append("on conflict (country_code, name) do update set slug = excluded.slug, region = coalesce(cities.region, excluded.region),"
             " map_x = excluded.map_x, map_y = excluded.map_y,\n"
             "  status = case when excluded.status = 'OPEN' and cities.status = 'PLANNED' then 'OPEN'::world_status else cities.status end;\n")
    L.append("insert into world_routes(code, name, via, from_city_id, to_city_id, region, distance_km, distance_source, status, unlock_level, game_route_id, description)")
    L.append("select v.code, v.name, v.via, a.id, b.id, v.region, v.km, v.src, v.status::world_status, v.lvl, v.game_route, v.descr from (values")
    rows = []
    for r, km, src, st in routes:
        via = "array[" + ",".join(q(x) for x in r["via"]) + "]"
        rows.append(f"  ({q(r['id'])}, {q(r['name'])}, {via}::text[], {q(r.get('region'))}, {km}::numeric, {q(src)}, {q(st)}, {r['unlockLevel']}, "
                    f"{q(r.get('gameRouteId'))}, {q(r.get('description'))})")
    L.append(",\n".join(rows))
    L.append(") as v(code, name, via, region, km, src, status, lvl, game_route, descr)")
    L.append("join cities a on a.slug = v.via[1] join cities b on a.slug <> b.slug and b.slug = v.via[array_length(v.via, 1)]")
    L.append("on conflict (code) do nothing;\n")
    return "\n".join(L)


def content_sql():
    d = json.load(open(os.path.join(RES, "Dashboard", "news.json"), encoding="utf-8"))
    L = ["-- GENERATED by tools/gen_game_seed.py from Resources/Dashboard/news.json. Do not edit by hand.",
         "-- Authored in-house content (source = 'authored'); it is not external news. Inserts missing rows only.", "",
         "insert into content_items(id, kind, category, title, body, image_key, priority, published, publish_at) values"]
    rows = []
    n = len(d["items"])
    for i, it in enumerate(d["items"]):
        rows.append(f"  ({q(it['id'])}, 'news', {q(it.get('kind', 'update'))}, {q(it['title'])}, {q(it['body'])}, {q(it.get('art'))}, {n - i}, true, {q(it['date'] + ' 00:00:00+00')})")
    L.append(",\n".join(rows))
    L.append("on conflict (id) do nothing;\n")
    return "\n".join(L)


def hero_sql():
    d = json.load(open(os.path.join(RES, "Dashboard", "hero.json"), encoding="utf-8"))
    L = ["-- GENERATED by tools/gen_game_seed.py from Resources/Dashboard/hero.json. Do not edit by hand.",
         "-- Authored hero banners for the dashboard (source = 'authored'). Inserts missing rows only.", "",
         "insert into content_items(id, kind, category, title, body, image_key, priority, published, publish_at, eyebrow, headline, headline_accent, action, button) values"]
    rows = []
    n = len(d["items"])
    for i, it in enumerate(d["items"]):
        rows.append(f"  ({q(it['id'])}, 'hero', 'update', {q(it['title'])}, {q(it['body'])}, {q(it.get('art'))}, {n - i}, true, {q(it['date'] + ' 00:00:00+00')}, "
                    f"{q(it['eyebrow'])}, {q(it['headline'])}, {q(it['accent'])}, {q(it['action'])}, {q(it['button'])})")
    L.append(",\n".join(rows))
    L.append("on conflict (id) do nothing;\n")
    return "\n".join(L)


def main():
    outputs = {"seed_world.sql": world_sql(), "seed_content.sql": content_sql() + "\n" + hero_sql()}
    stale = []
    for name, text in outputs.items():
        p = os.path.join(OUT, name)
        if "--check" in sys.argv:
            if not os.path.exists(p) or open(p, encoding="utf-8").read() != text:
                stale.append(name)
        else:
            open(p, "w", encoding="utf-8").write(text)
            print("wrote", p)
    if stale:
        print("STALE (run: python3 tools/gen_game_seed.py): " + ", ".join(stale)); sys.exit(1)
    if "--check" in sys.argv:
        print("seeds are up to date")


main()
