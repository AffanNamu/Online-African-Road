#!/usr/bin/env python3
"""Checks the RELEASE CHAIN of every produced asset of the private asset repository (owner requirement, 2026-11-07: "for all future asset releases, preserve the complete chain: reference -> Blender source -> exported files ->
Unity prefab -> validation -> in-game review"). The registry's own header states the same chain. For each registry asset that has a Blender source, six links are checked against a checkout of an `assets/...` branch of ARO-CONTENT:

  reference       every concept id of the asset exists in the reference register (docs/kano/reference_register.json of the game repository); an asset with no concept image but registered `documentaryReferences` (text or scholarly sources, kind documentary_source) is ok with that detail; an asset with neither must record why in its flags (a documented reference gap M-nn, or an owner request) and stays OPEN, never ok
  blender_source  the .blend named by the registry exists in the checkout
  export          the FBX, the GLB and the package manifest of the registry's export exist
  unity_prefab    the Unity import report named by the registry has an entry for the asset whose LOD triangles equal the registry's and whose material count equals the registry's (the prefab itself is generated by the importer in CI and is
                  never committed; the import report is its record)
  validation      the Blender validation report exists and passed
  in_game_review  the registry records a visual review (owner decision) and, with --reviews, the pictures of the run that imported the asset are preserved; until the owner has looked, this link is OPEN, never ok

A link is ok, open (not yet reached: legitimate), missing or mismatch (broken: the exit code is 1). It never changes a registry and never marks anything approved.
  python3 tools/release_chain.py --content <ARO-CONTENT checkout> [--reviews <dir with runs.json>] [--refs docs/kano/reference_register.json] [--json out.json]"""
from __future__ import annotations
import argparse, json, re, sys
from pathlib import Path

LINKS = ["reference", "blender_source", "export", "unity_prefab", "validation", "in_game_review"]


def load_registry(content: Path) -> list:
    d = json.loads((content / "registry" / "asset_registry.json").read_text())
    a = d["assets"] if isinstance(d, dict) else d
    return list(a.values()) if isinstance(a, dict) else a


def check_asset(a: dict, content: Path, refs: set, imports: dict, review_runs: set) -> dict:
    """{link: (state, detail)} for one registry entry."""
    out: dict = {}
    c = a.get("concepts") or []; dr = a.get("documentaryReferences") or []
    gap = re.search(r"\bM-\d+\b", a.get("flags") or "")
    if not c and dr:
        bad = [x for x in dr if x not in refs]
        out["reference"] = ("mismatch", f"documentary reference not in the register: {bad}") if bad else ("ok", "documentary references only (no concept image, no photograph): " + ", ".join(dr) + (f"; gap {gap.group(0)} stays partly open" if gap else ""))
    elif not c:
        fl = (a.get("flags") or "").lower()
        out["reference"] = ("open", "no concept id; documented reference gap " + gap.group(0) + ": a flagged design interpretation") if gap else ("open", "no concept id; recorded as an owner request") if "owner" in fl else ("missing", "no concept id and no recorded reason (reference gap or owner request)")
    else:
        bad = [x for x in c + dr if x not in refs]; out["reference"] = ("mismatch", f"not in the reference register: {bad}") if bad else ("ok", ", ".join(c + dr))
    src = a.get("blenderSource"); out["blender_source"] = ("ok", src) if src and (content / src).is_file() else ("missing", str(src))
    exp = a.get("export")
    if exp:
        p = content / exp; want = [p, p.with_suffix(".glb"), p.with_suffix(".manifest.json")]; gone = [str(w.relative_to(content)) for w in want if not w.is_file()]
        out["export"] = ("missing", "missing: " + ", ".join(gone)) if gone else ("ok", exp)
    else: out["export"] = ("missing", "no export")
    v = a.get("validation") or {}; vp = v.get("blender")
    if vp and (content / vp).is_file():
        try: out["validation"] = ("ok", vp) if json.loads((content / vp).read_text()).get("passed") is True else ("mismatch", f"{vp} did not pass")
        except ValueError: out["validation"] = ("mismatch", f"{vp} is not JSON")
    else: out["validation"] = ("missing", str(vp))
    up = v.get("unityImport")
    if not up: out["unity_prefab"] = ("open", "not imported into Unity yet") if a.get("status") in ("blender_validation_passed", "materials_completed", "detailed_modelling_completed", "blockout_completed") else ("missing", "no import report named")
    else:
        rep = imports.get(up)
        if rep is None: out["unity_prefab"] = ("missing", f"import report {up} not found")
        elif a["id"] not in rep: out["unity_prefab"] = ("missing", f"no entry for the asset in {up}")
        else:
            e = rep[a["id"]]; want_l, want_m = a.get("lodTriangles") or [l.get("triangles") for l in a.get("lods", [])], len(a.get("materials") or [])
            if list(e.get("lodTriangles", [])) != list(want_l): out["unity_prefab"] = ("mismatch", f"Unity LOD triangles {e.get('lodTriangles')} != registry {want_l}")
            elif e.get("materials") != want_m: out["unity_prefab"] = ("mismatch", f"Unity materials {e.get('materials')} != registry {want_m}")
            else: out["unity_prefab"] = ("ok", f"{up}: LOD triangles {want_l}, {want_m} materials equal the Blender record")
    vr = v.get("visualReview")
    if vr: out["in_game_review"] = ("ok", vr) if (content / vr).is_file() else ("missing", f"{vr} not found")
    else:
        run = Path(up).stem.rsplit("_", 1)[-1] if up else ""
        out["in_game_review"] = ("open", "owner's review pending" + ("; the pictures of the importing run are preserved" if run in review_runs else "; no preserved pictures of the importing run"))
    return out


def load_imports(content: Path) -> dict:
    out = {}
    for f in sorted((content / "unity" / "import_reports").glob("*.json")) if (content / "unity" / "import_reports").is_dir() else []:
        try: d = json.loads(f.read_text())
        except ValueError: continue
        out[f"unity/import_reports/{f.name}"] = d.get("assets", d)
    return out


def run(content: Path, refs_file: Path, reviews: Path | None) -> tuple[list, dict]:
    refs = {r["id"] for r in json.loads(refs_file.read_text())["references"]}
    review_runs = {r["run_id"] for r in json.loads((reviews / "runs.json").read_text())["runs"]} if reviews and (reviews / "runs.json").is_file() else set()
    imports = load_imports(content); rows = []
    for a in load_registry(content):
        if a.get("blenderSource"): rows.append({"id": a["id"], "status": a.get("status"), "library": a.get("library"), "links": check_asset(a, content, refs, imports, review_runs)})
    count = {s: sum(1 for r in rows for l in r["links"].values() if l[0] == s) for s in ("ok", "open", "missing", "mismatch")}
    return rows, count


def main() -> int:
    ap = argparse.ArgumentParser(); ap.add_argument("--content", required=True); ap.add_argument("--reviews", default=""); ap.add_argument("--refs", default=str(Path(__file__).resolve().parent.parent / "docs/kano/reference_register.json")); ap.add_argument("--json", default="")
    a = ap.parse_args(); rows, count = run(Path(a.content), Path(a.refs), Path(a.reviews) if a.reviews else None)
    print(f"{len(rows)} produced assets, {len(rows) * len(LINKS)} links: " + ", ".join(f"{k} {v}" for k, v in count.items()))
    for r in rows:
        broken = {k: v for k, v in r["links"].items() if v[0] in ("missing", "mismatch")}
        for k, (s, d) in broken.items(): print(f"  BROKEN {r['id']} {k}: {s}: {d}")
    complete = [r["id"] for r in rows if all(v[0] == "ok" for v in r["links"].values())]
    print(f"chain complete through the in-game review (owner decision recorded): {len(complete)} of {len(rows)}; every other asset is open only at the links shown as open")
    if a.json: Path(a.json).write_text(json.dumps({"summary": count, "assets": rows}, indent=1))
    return 1 if count["missing"] or count["mismatch"] else 0


if __name__ == "__main__":
    sys.exit(main())
